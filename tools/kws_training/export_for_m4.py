#!/usr/bin/env python3
"""
Export quantized TFLite model for M4 deployment.

Steps:
  1. Run stedgeai/stm32ai CLI to generate network.c / network_data.c
  2. Generate kws_model_meta.h from config + quantization params
  3. Generate kws_labels.json (CA7 mirror of the label table)
  4. Copy generated files to their target paths in the repo

Usage:
    python3 export_for_m4.py [--config config.yaml] [--skip-cubeai]
"""

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml


def load_config(path: str) -> dict:
    with open(path) as f:
        return yaml.safe_load(f)


# ── C header generation ───────────────────────────────────────────────────────
def build_meta_header(cfg: dict, quant: dict) -> str:
    """Generate kws_model_meta.h content."""
    classes = cfg["classes"]
    num_classes = len(classes)
    trigger_classes = cfg.get("trigger_classes", [])

    # Build trigger mask (bitmask, 1 << class_id)
    trigger_mask = 0
    for label in trigger_classes:
        if label in classes:
            trigger_mask |= (1 << classes.index(label))

    # Build label enum names: "xiao_wang" → KWS_CLASS_XIAOWANG
    def to_enum(label: str) -> str:
        return "KWS_CLASS_" + label.upper()

    # Build label string array
    label_strings = ", ".join(f'"{lbl}"' for lbl in classes)

    # Quantization params
    in_scale = quant["in_scale"]
    in_zero_pt = int(quant["in_zero_pt"])
    out_scale = quant["out_scale"]
    out_zero_pt = int(quant["out_zero_pt"])

    # Convert input scale to integer approximation (× 1000, matching kws.h style).
    # Training data was normalized by feat_max before quantization, so the effective
    # scale seen by the M4 frontend output is: in_scale * feat_max.
    feat_max = quant.get("feat_max", 1.0)
    effective_scale = in_scale * feat_max if feat_max > 0 else in_scale
    in_scale_inv_x1000 = round(1000.0 / effective_scale) if effective_scale > 0 else 9831
    # Output: convert scale to integer divisor (power of 2 nearest to 1/scale)
    out_scale_div = round(1.0 / out_scale) if out_scale > 0 else 256

    lines = [
        "/* kws_model_meta.h — AUTO-GENERATED by tools/kws_training/export_for_m4.py",
        " * DO NOT EDIT MANUALLY — re-run the training pipeline to update.",
        " *",
        " * This file is the single source of truth for model-specific constants.",
        " * All KWS_CLASS_* / KWS_NUM_CLASSES / quantization macros live here, NOT in kws.h.",
        " */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "/* ---- Class definitions ------------------------------------------------- */",
        f"#define KWS_NUM_CLASSES  {num_classes}u",
        "",
    ]

    for i, label in enumerate(classes):
        lines.append(f"#define {to_enum(label):30s} {i}u")

    lines += [
        "",
        "/* Label strings (indexed by class ID) */",
        f"static const char * const kws_class_labels[KWS_NUM_CLASSES] = {{ {label_strings} }};",
        "",
        "/* Trigger mask: OR of (1 << class_id) for classes that fire MSG_WAKE */",
        f"#define KWS_TRIGGER_CLASS_MASK  0x{trigger_mask:02X}u",
        "",
        "/* Minimum confidence (0-100) required to report a detection */",
        f"#define KWS_DETECT_THRESHOLD    {cfg['detect_threshold']}u",
        "",
        "/* Sliding-average window for score smoothing */",
        f"#define KWS_SMOOTH_FRAMES       {cfg['smooth_frames']}u",
        "",
        "/* ---- Quantization parameters (from quantize.py) ------------------------ */",
        "/*",
        f" * Input:  scale={in_scale:.8f}  zero_point={in_zero_pt}",
        f" * Output: scale={out_scale:.8f}  zero_point={out_zero_pt}",
        " *",
        " * Integer input conversion (avoids float on M4):",
        f" *   int8 = (uint16 * {in_scale_inv_x1000} + 500) / 1000 + ({in_zero_pt})",
        " */",
        f"#define KWS_IN_SCALE_INV_x1000  {in_scale_inv_x1000}",
        f"#define KWS_IN_ZERO_PT          ({in_zero_pt})",
        f"#define KWS_OUT_ZERO_PT         ({out_zero_pt})",
        f"#define KWS_OUT_SCALE_DIV       {out_scale_div}",
        "",
        "/* ---- Feature dimensions (must match kws_frontend.c) -------------------- */",
        f"#define KWS_NUM_FRAMES          {cfg['num_frames']}u",
        f"#define KWS_NUM_FEATURES        {cfg['num_mel_bins']}u",
        "",
    ]

    return "\n".join(lines)


def build_labels_json(cfg: dict) -> str:
    classes = cfg["classes"]
    text_map = cfg.get("text_map", {})
    labels = {}
    for i, label in enumerate(classes):
        # Use Chinese text if available, otherwise use ASCII label
        labels[str(i)] = text_map.get(label, label)
    return json.dumps(labels, ensure_ascii=False, indent=2)


# ── stedgeai / stm32ai CLI ────────────────────────────────────────────────────
def run_cubeai(tflite_path: Path, out_dir: Path, model_name: str,
               cli_path: str) -> bool:
    """
    Run stedgeai (X-CUBE-AI 10.x / v2.x) to generate C source.
    Prints stdout/stderr so failures are diagnosable.
    Returns True on success.
    """
    cli = cli_path  # use absolute path directly (already verified in config)

    # stedgeai 10.x (v2.x) generate command
    cmd = [
        cli, "generate",
        "--target", "stm32",
        "--name", model_name,
        "--model", str(tflite_path),
        "--output", str(out_dir),
    ]

    print(f"  [cubeai] running: {' '.join(cmd)}")
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
        if result.stdout:
            for line in result.stdout.splitlines():
                print(f"    {line}")
        if result.returncode == 0:
            print("  [cubeai] success")
            return True
        else:
            print(f"  [cubeai] failed (exit {result.returncode})")
            if result.stderr:
                print(result.stderr[:600])
            return False
    except FileNotFoundError:
        print(f"  [cubeai] binary not found: {cli!r}")
        return False
    except subprocess.TimeoutExpired:
        print("  [cubeai] timeout after 180s")
        return False


def copy_cubeai_outputs(tmp_dir: Path, network_src_dir: Path,
                        model_name: str) -> bool:
    """Copy network.c / network_data.c / network.h etc. to micro_speech/.
    stedgeai 10.x places files under <output>/<model_name>/ — search recursively."""
    # Copy all .c and .h files stedgeai generated (version-agnostic)
    all_files = list(tmp_dir.rglob("*"))
    print(f"  [cubeai] generated {len(all_files)} files under {tmp_dir}")

    copied = False
    for src in all_files:
        if src.is_file() and src.suffix in (".c", ".h"):
            dst = network_src_dir / src.name
            shutil.copy2(str(src), str(dst))
            print(f"    {src.name} → {dst}")
            copied = True
    return copied


# ── Main ──────────────────────────────────────────────────────────────────────
def main(config_path: str, skip_cubeai: bool):
    cfg = load_config(config_path)
    base_dir = Path(config_path).parent
    model_dir = base_dir / cfg["train"]["model_dir"]
    tflite_path = base_dir / cfg["export"]["tflite_path"]
    network_src_dir = (base_dir / cfg["export"]["network_src_dir"]).resolve()
    meta_header_dst = (base_dir / cfg["export"]["meta_header_dst"]).resolve()
    labels_json_dst = (base_dir / cfg["export"]["labels_json_dst"]).resolve()

    # Load quantization params from previous step
    quant_json = model_dir / "quant_params.json"
    if not quant_json.exists():
        print(f"Error: {quant_json} not found — run quantize.py first",
              file=sys.stderr)
        sys.exit(1)
    with open(quant_json) as f:
        quant = json.load(f)

    if not tflite_path.exists():
        print(f"Error: {tflite_path} not found — run quantize.py first",
              file=sys.stderr)
        sys.exit(1)

    # ── Step 1: X-CUBE-AI code generation ────────────────────────────────────
    if not skip_cubeai:
        print(f"\n=== Step 1: X-CUBE-AI code generation ===")
        model_name = cfg["export"]["cubeai_model_name"]
        cli_path = cfg["export"]["cubeai_cli"]
        network_src_dir.mkdir(parents=True, exist_ok=True)

        with tempfile.TemporaryDirectory() as tmp:
            tmp_dir = Path(tmp)
            ok = run_cubeai(tflite_path, tmp_dir, model_name, cli_path)
            if ok:
                copy_cubeai_outputs(tmp_dir, network_src_dir, model_name)
            else:
                print("\n  [warn] stedgeai not available or failed.")
                print("  Manual steps:")
                print(f"    1. Open STM32CubeIDE → X-CUBE-AI → Add .tflite model")
                print(f"    2. Model file: {tflite_path}")
                print(f"    3. Output name: {model_name}")
                print(f"    4. Copy generated files to: {network_src_dir}")
                print("  Or install stedgeai:")
                print("    https://www.st.com/en/embedded-software/x-cube-ai.html")
    else:
        print("\n=== Step 1: X-CUBE-AI skipped (--skip-cubeai) ===")

    # ── Step 2: Generate kws_model_meta.h ────────────────────────────────────
    print(f"\n=== Step 2: Generate kws_model_meta.h ===")
    header_content = build_meta_header(cfg, quant)
    meta_header_dst.parent.mkdir(parents=True, exist_ok=True)
    meta_header_dst.write_text(header_content)
    print(f"  Written: {meta_header_dst}")

    # Print summary of generated macros
    classes = cfg["classes"]
    trigger_classes = cfg.get("trigger_classes", [])
    print(f"  KWS_NUM_CLASSES = {len(classes)}")
    for i, lbl in enumerate(classes):
        mark = " ← trigger" if lbl in trigger_classes else ""
        print(f"    [{i}] {lbl}{mark}")
    feat_max = quant.get("feat_max", 1.0)
    print(f"  KWS_IN_SCALE_INV_x1000 = {round(1000 / (quant['in_scale'] * feat_max))}")
    print(f"  KWS_OUT_SCALE_DIV       = {round(1/quant['out_scale'])}")

    # ── Step 3: Generate kws_labels.json (CA7 side) ──────────────────────────
    print(f"\n=== Step 3: Generate kws_labels.json ===")
    labels_content = build_labels_json(cfg)
    labels_json_dst.parent.mkdir(parents=True, exist_ok=True)
    labels_json_dst.write_text(labels_content, encoding="utf-8")
    print(f"  Written: {labels_json_dst}")
    print(f"  Content: {labels_content}")

    print("\n=== Export complete ===")
    print(f"  kws_model_meta.h  → {meta_header_dst}")
    print(f"  kws_labels.json   → {labels_json_dst}")
    if not skip_cubeai:
        print(f"  network.c/data.c  → {network_src_dir}")
    print("\nNext steps:")
    print("  1. Build M4 firmware:  ./build.sh m4 Release")
    print("  2. Flash:              ./build.sh flash full")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="config.yaml")
    parser.add_argument("--skip-cubeai", action="store_true",
                        help="Skip stedgeai invocation (generate meta header only)")
    args = parser.parse_args()
    main(args.config, args.skip_cubeai)
