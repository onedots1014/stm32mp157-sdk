    hdma_sai1_a.Init.Request             = DMA_REQUEST_SAI1_A;
    hdma_sai1_a.Init.Direction           = DMA_MEMORY_TO_PERIPH;
    hdma_sai1_a.Init.PeriphInc           = DMA_PINC_DISABLE;
    hdma_sai1_a.Init.MemInc              = DMA_MINC_ENABLE;
